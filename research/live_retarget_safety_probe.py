def process_alive(process_id: int) -> bool:
    """Read one supplied Windows process handle without changing it."""
    if sys.platform != "win32":
        return True
    handle = ctypes.windll.kernel32.OpenProcess(0x00100000, False, process_id)
    if not handle:
        return False
    try:
        return ctypes.windll.kernel32.WaitForSingleObject(handle, 0) == 0x00000102
    finally:
        ctypes.windll.kernel32.CloseHandle(handle)


def _default_wait(event: threading.Event, timeout: float) -> None:
    event.wait(max(0.0, timeout))


def execute_probe(
    sdk_module: Any, *, port: int, process_id: int, config: ProbeConfig,
    clock: Clock = time.monotonic, waiter: Waiter = _default_wait,
    process_guard: ProcessGuard = process_alive,
    stop_event: Optional[threading.Event] = None,
) -> dict[str, Any]:
    """Open one SDK client once, run the bounded probe, and close it once."""
    probe = LiveRetargetSafetyProbe(config, clock=clock)
    stop, sdk, run_started = stop_event or threading.Event(), None, None
    try:
        try:
            probe.process_alive_start = probe.process_alive_end = bool(process_guard(process_id))
        except Exception:
            probe._abort(AbortReason.PROCESS_STATE_AMBIGUOUS)
        if probe.abort_reason is AbortReason.NONE and not probe.process_alive_start:
            probe._abort(AbortReason.PROCESS_NOT_ALIVE)
        if probe.abort_reason is AbortReason.NONE:
            probe.lifecycle["sdk_constructor_attempts"] += 1
            try:
                sdk = sdk_module.RebocapWsSdk(
                    coordinate_type=sdk_module.CoordinateType.UnityCoordinate,
                    use_global_rotation=True,
                )
                probe.lifecycle["sdk_client_instances"] += 1
            except Exception:
                probe._abort(AbortReason.SDK_CONSTRUCTION_FAILED)
        if probe.abort_reason is AbortReason.NONE:
            try:
                sdk.set_pose_msg_callback(probe.on_pose)
                sdk.set_exception_close_callback(probe.on_sdk_close)
            except Exception:
                probe._abort(AbortReason.SDK_CALLBACK_REGISTRATION_FAILED)
        if probe.abort_reason is AbortReason.NONE:
            try:
                run_started = _finite(clock(), "run_started")
                probe.record_run_start(run_started)
                result = sdk.open(port)
            except Exception:
                probe.lifecycle["sdk_open_attempts"] += 1
                probe._abort(AbortReason.SDK_OPEN_FAILED)
            else:
                if not probe.record_sdk_open_result(result):
                    probe._abort(AbortReason.SDK_OPEN_FAILED)
        if probe.abort_reason is AbortReason.NONE:
            deadline, period = run_started + config.duration_seconds, 1.0 / config.consumer_hz
            while probe.abort_reason is AbortReason.NONE:
                if stop.is_set():
                    probe.request_user_stop()
                    break
                try:
                    probe.process_alive_end = bool(process_guard(process_id))
                except Exception:
                    probe._abort(AbortReason.PROCESS_STATE_AMBIGUOUS)
                    break
                if not probe.process_alive_end:
                    probe._abort(AbortReason.PROCESS_NOT_ALIVE)
                    break
                try:
                    now = _finite(clock(), "loop_monotonic")
                except ValueError:
                    probe._abort(AbortReason.INVALID_RECEIVE_TIMESTAMP)
                    break
                if now >= deadline:
                    break
                probe.wake.clear()
                probe.process_latest()
                remaining = deadline - _finite(clock(), "loop_monotonic")
                if probe.abort_reason is not AbortReason.NONE or remaining <= 1e-9:
                    break
                waiter(probe.wake, min(period, remaining))
            if probe.abort_reason is AbortReason.NONE:
                try:
                    probe.process_alive_end = bool(process_guard(process_id))
                except Exception:
                    probe._abort(AbortReason.PROCESS_STATE_AMBIGUOUS)
                if not probe.process_alive_end:
                    probe._abort(AbortReason.PROCESS_NOT_ALIVE)
                else:
                    probe.process_latest()
                    if probe.abort_reason is AbortReason.NONE:
                        probe.finish_normal_observation()
    finally:
        if sdk is not None:
            probe.record_close_start(clock())
            probe.lifecycle["sdk_close_attempts"] += 1
            try:
                sdk.close()
                probe.lifecycle["sdk_close_successes"] += 1
            except Exception:
                probe._abort(AbortReason.SDK_CLOSE_FAILED)
        probe.finish_disconnected_clear()
    return probe.aggregate_result()


def _parse_args(argv: Optional[list[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdk-root", type=Path, required=True)
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--process-id", type=int, required=True)
    parser.add_argument("--duration-seconds", type=float, default=20.0)
    parser.add_argument("--stale-after-seconds", type=float, default=0.250)
    parser.add_argument("--quaternion-norm-tolerance", type=float, default=1e-4)
    parser.add_argument("--consumer-hz", type=float, default=30.0)
    parser.add_argument("--pure-pipeline-p99-budget-ms", type=float, default=10.0)
    args = parser.parse_args(argv)
    if not 1 <= args.port <= 65535 or args.process_id <= 0:
        parser.error("port and process-id must be positive and in range")
    try:
        args.config = ProbeConfig(
            duration_seconds=args.duration_seconds,
            stale_after_seconds=args.stale_after_seconds,
            quaternion_norm_tolerance=args.quaternion_norm_tolerance,
            consumer_hz=args.consumer_hz,
            pure_pipeline_p99_budget_ms=args.pure_pipeline_p99_budget_ms,
        )
    except ValueError as error:
        parser.error(str(error))
    return args


def _import_failure(config: ProbeConfig) -> dict[str, Any]:
    probe = LiveRetargetSafetyProbe(config)
    probe._abort(AbortReason.SDK_IMPORT_FAILED)
    return probe.aggregate_result()


def main(argv: Optional[list[str]] = None) -> int:
    args, stop = _parse_args(argv), threading.Event()
    signal.signal(signal.SIGINT, lambda _signum, _frame: stop.set())
    signal.signal(signal.SIGTERM, lambda _signum, _frame: stop.set())
    sys.path.insert(0, str(args.sdk_root.resolve()))
    try:
        from rebocap_ws_sdk import rebocap_ws_sdk
    except Exception:
        report = _import_failure(args.config)
    else:
        report = execute_probe(
            rebocap_ws_sdk, port=args.port, process_id=args.process_id,
            config=args.config, stop_event=stop,
        )
    print("RESULT_JSON=" + json.dumps(report, sort_keys=True, separators=(",", ":")))
    return 0 if report["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
