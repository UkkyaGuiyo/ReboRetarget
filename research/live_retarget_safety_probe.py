def _finite(value: Any, label: str) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{label} must be finite and not Boolean")
    try:
        result = float(value)
    except (TypeError, ValueError) as error:
        raise ValueError(f"{label} must be finite") from error
    if not math.isfinite(result):
        raise ValueError(f"{label} must be finite")
    return result


@dataclass(frozen=True, slots=True)
class ProbeConfig:
    duration_seconds: float = 20.0
    stale_after_seconds: float = 0.250
    quaternion_norm_tolerance: float = 1e-4
    consumer_hz: float = 30.0
    pure_pipeline_p99_budget_ms: float = 10.0
    minimum_callbacks: int = 100
    minimum_callback_hz: float = 45.0
    maximum_callback_hz: float = 75.0

    def __post_init__(self) -> None:
        numeric = {
            name: _finite(getattr(self, name), name)
            for name in (
                "duration_seconds",
                "stale_after_seconds",
                "quaternion_norm_tolerance",
                "consumer_hz",
                "pure_pipeline_p99_budget_ms",
                "minimum_callback_hz",
                "maximum_callback_hz",
            )
        }
        if not 1.0 <= numeric["duration_seconds"] <= 60.0:
            raise ValueError("duration_seconds must be between 1 and 60")
        if any(
            numeric[name] <= 0.0
            for name in (
                "stale_after_seconds",
                "quaternion_norm_tolerance",
                "consumer_hz",
                "pure_pipeline_p99_budget_ms",
                "minimum_callback_hz",
            )
        ):
            raise ValueError("probe thresholds and rates must be positive")
        if numeric["maximum_callback_hz"] < numeric["minimum_callback_hz"]:
            raise ValueError("callback Hz acceptance range is invalid")
        if (
            isinstance(self.minimum_callbacks, bool)
            or not isinstance(self.minimum_callbacks, int)
            or self.minimum_callbacks <= 0
        ):
            raise ValueError("minimum_callbacks must be a positive integer")
        for name, value in numeric.items():
            object.__setattr__(self, name, value)


class _Histogram:
    """Bounded-memory percentile approximation."""

    def __init__(self, width: float, maximum: float) -> None:
        self.width = width
        self.maximum = maximum
        self.bins = [0] * (math.ceil(maximum / width) + 1)
        self.count = self.overflow = 0
        self.total = 0.0
        self.minimum = math.inf
        self.maximum_seen = -math.inf

    def add(self, value: float) -> None:
        if not math.isfinite(value) or value < 0.0:
            return
        self.count += 1
        self.total += value
        self.minimum = min(self.minimum, value)
        self.maximum_seen = max(self.maximum_seen, value)
        if value > self.maximum:
            self.overflow += 1
        else:
            self.bins[min(int(value / self.width), len(self.bins) - 1)] += 1

    def percentile(self, fraction: float) -> Optional[float]:
        target = max(1, math.ceil(self.count * fraction))
        seen = 0
        for index, amount in enumerate(self.bins):
            seen += amount
            if seen >= target:
                return round(index * self.width, 6)
        return round(self.maximum_seen, 6) if self.count else None

    def summary(self) -> dict[str, Any]:
        return {
            "count": self.count,
            "mean": round(self.total / self.count, 6) if self.count else None,
            "min": round(self.minimum, 6) if self.count else None,
            "p50": self.percentile(0.50),
            "p95": self.percentile(0.95),
            "p99": self.percentile(0.99),
            "max": round(self.maximum_seen, 6) if self.count else None,
            "overflow_count": self.overflow,
        }


class _InputError(Exception):
    def __init__(self, reason: AbortReason) -> None:
        super().__init__(reason.value)
        self.reason = reason


